// Writes test/dictionary_vectors.dart: a dictionary, its delivery form, and
// frames compressed against it by the protocol's own DeflateFrameCodec, so the
// Dart decoder is checked against what a server produces.
//
//	cd tool/dictionary_vectors && go run . ../../test/dictionary_vectors.dart &&
//	  dart format ../../test/dictionary_vectors.dart
package main

import (
	"crypto/sha256"
	"encoding/base64"
	"fmt"
	"os"
	"strings"

	"github.com/centrifugal/protocol"
)

func list(b []byte) string {
	parts := make([]string, len(b))
	for i, x := range b {
		parts[i] = fmt.Sprint(x)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func main() {
	dict := []byte(`{"type":"quote","symbol":"BTC-USD","bid":,"ask":,"last":,"volume":,"change24h":,"ts":}{"push":{"channel":"prices:board","pub":{"data":`)
	sum := sha256.Sum256(dict)
	id := base64.RawURLEncoding.EncodeToString(sum[:12])
	codec := protocol.NewDeflateFrameCodec(id, dict, 7)

	enc := protocol.NewProtobufReplyEncoder()
	var frames [][]byte
	for i, sym := range []string{"BTC-USD", "ETH-USD"} {
		data := fmt.Sprintf(`{"type":"quote","symbol":"%s","bid":%d.5,"ask":%d.7,"last":%d.6,"volume":%d,"change24h":1.2,"ts":1793042757287}`, sym, 100+i, 100+i, 100+i, 3000+i)
		b, err := enc.Encode(&protocol.Reply{Push: &protocol.Push{Channel: "prices:board", Pub: &protocol.Publication{Data: []byte(data)}}})
		if err != nil {
			panic(err)
		}
		de := protocol.NewProtobufDataEncoder()
		_ = de.Encode(b)
		frames = append(frames, append([]byte(nil), de.Finish()...))
	}

	var out strings.Builder
	out.WriteString("// Generated by tool/dictionary_vectors with github.com/centrifugal/protocol\n")
	out.WriteString("// (DeflateFrameCodec, DeflateDictionary). Do not edit.\n\n")
	fmt.Fprintf(&out, "const vectorDictionaryId = '%s';\n\n", id)
	fmt.Fprintf(&out, "const vectorDictionary = %s;\n\n", list(dict))
	delivered := protocol.DeflateDictionary(dict, 9)
	fmt.Fprintf(&out, "const vectorDictionaryDelivered = %s;\n\n", list(delivered))
	fmt.Fprintf(&out, "const vectorDictionaryDeliveredB64 = '%s';\n\n", base64.StdEncoding.EncodeToString(delivered))
	out.WriteString("// Protobuf transport frames, uncompressed and as the codec sends them.\n")
	out.WriteString("const vectorFrames = [\n")
	for _, f := range frames {
		fmt.Fprintf(&out, "  %s,\n", list(f))
	}
	out.WriteString("];\n\nconst vectorCompressedFrames = [\n")
	for _, f := range frames {
		c := codec.Compress(nil, f)
		if c[0] != protocol.FrameCodecCompressed {
			panic("frame not compressed")
		}
		fmt.Fprintf(&out, "  %s,\n", list(c))
	}
	out.WriteString("];\n")
	if err := os.WriteFile(os.Args[1], []byte(out.String()), 0o644); err != nil {
		panic(err)
	}
}
